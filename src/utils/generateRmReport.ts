import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import moment from "moment";

interface DashboardData {
   customerCount: number;
   rmTarget: number;
   rmRecoveredAmount: number;
   rmOutStandingAmount: number;
   rmOverdueAmount: number;
   chartData?: any[];
   noOfOverdueAccounts?: any[];
}

interface ReportOptions {
   title?: string;
   companyName?: string;
   reportDate?: string;
   generatedBy?: string;
   bankName?: string;
}

// Format currency in BDT with full format
const formatBDT = (value: number): string => {
   return `BDT ${Number(value).toLocaleString("en-BD")}`;
};

// Format number with commas
const formatNumber = (value: number): string => {
   return Number(value).toLocaleString("en-BD");
};

/**
 * Generate Professional RM Dashboard PDF Report (Black & White, Table Only)
 * @param data Dashboard data from API
 * @param options Report customization options
 */
export const generateRMDashboardReport = (
   data: DashboardData,
   options: ReportOptions = {}
): void => {
   const {
      title = "Recovery Management Dashboard Report",
      companyName = "PRIME TWO MILLION (P2M) BANK LIMITED",
      reportDate = moment().format("DD MMMM YYYY"),
      generatedBy = "System Generated",
      bankName = "P2M Bank",
   } = options;

   const pdf = new jsPDF({
      orientation: "portrait",
      unit: "mm",
      format: "a4",
   });

   const pageWidth = pdf.internal.pageSize.getWidth();
   const pageHeight = pdf.internal.pageSize.getHeight();
   let yPosition = 15;

   // Set default font
   pdf.setFont("Arial", "normal");
   pdf.setTextColor(0, 0, 0);

   // Header Section - Professional Bank Header
   pdf.setFontSize(16);
   pdf.setFont("Arial", "bold");
   pdf.text(companyName, pageWidth / 2, yPosition, { align: "center" });

   yPosition += 8;
   pdf.setFontSize(12);
   pdf.setFont("Arial", "bold");
   pdf.text(title, pageWidth / 2, yPosition, { align: "center" });

   yPosition += 7;
   pdf.setFontSize(9);
   pdf.setFont("Arial", "normal");
   pdf.text(`Report Date: ${reportDate}`, pageWidth / 2, yPosition, {
      align: "center",
   });

   yPosition += 5;
   pdf.text(
      `Generated By: ${generatedBy} | Generated On: ${moment().format("DD MMM YYYY HH:mm:ss")}`,
      pageWidth / 2,
      yPosition,
      {
         align: "center",
      }
   );

   yPosition += 10;

   // Add horizontal line
   pdf.setDrawColor(0, 0, 0);
   pdf.setLineWidth(0.5);
   pdf.line(15, yPosition, pageWidth - 15, yPosition);

   yPosition += 8;

   // 1. EXECUTIVE SUMMARY TABLE
   pdf.setFontSize(11);
   pdf.setFont("Arial", "bold");
   pdf.text("1. EXECUTIVE SUMMARY", 15, yPosition);
   yPosition += 6;

   const executiveSummaryData = [
      ["Particulars", "Value"],
      ["Total Assigned Customers", data.customerCount.toString()],
      ["Annual Recovery Target", formatBDT(data.rmTarget)],
      ["Amount Recovered", formatBDT(data.rmRecoveredAmount)],
      ["Outstanding Amount", formatBDT(data.rmOutStandingAmount)],
      ["Overdue Amount", formatBDT(data.rmOverdueAmount)],
   ];

   autoTable(pdf, {
      startY: yPosition,
      head: [executiveSummaryData[0]],
      body: executiveSummaryData.slice(1),
      margin: { left: 15, right: 15 },
      theme: "grid",
      headStyles: {
         fillColor: [0, 0, 0],
         textColor: [255, 255, 255],
         fontSize: 10,
         fontStyle: "bold",
         halign: "left",
         valign: "middle",
      },
      bodyStyles: {
         fontSize: 9,
         halign: "left",
         valign: "middle",
      },
      alternateRowStyles: {
         fillColor: [245, 245, 245],
      },
      columnStyles: {
         0: { cellWidth: 100 },
         1: { cellWidth: 70 },
      },
      styles: {
         lineColor: [0, 0, 0],
         lineWidth: 0.5,
      },
   });

   yPosition = (pdf as any).lastAutoTable.finalY + 12;

   // Check if we need a new page
   if (yPosition > pageHeight - 60) {
      pdf.addPage();
      yPosition = 15;
   }

   // 2. DETAILED KEY PERFORMANCE INDICATORS
   pdf.setFontSize(11);
   pdf.setFont("Arial", "bold");
   pdf.text("2. DETAILED KEY PERFORMANCE INDICATORS", 15, yPosition);
   yPosition += 6;

   const kpiTableData = [
      ["Performance Indicator", "Amount (BDT)", "Status Remark"],
      ["Amount Successfully Recovered", formatBDT(data.rmRecoveredAmount), "Positive"],
      ["Outstanding Amount (Pending Recovery)", formatBDT(data.rmOutStandingAmount), "Pending"],
      ["Overdue Amount (Past Due)", formatBDT(data.rmOverdueAmount), "Critical"],
   ];

   autoTable(pdf, {
      startY: yPosition,
      head: [kpiTableData[0]],
      body: kpiTableData.slice(1),
      margin: { left: 15, right: 15 },
      theme: "grid",
      headStyles: {
         fillColor: [0, 0, 0],
         textColor: [255, 255, 255],
         fontSize: 10,
         fontStyle: "bold",
         halign: "left",
         valign: "middle",
      },
      bodyStyles: {
         fontSize: 9,
         halign: "left",
         valign: "middle",
      },
      alternateRowStyles: {
         fillColor: [245, 245, 245],
      },
      styles: {
         lineColor: [0, 0, 0],
         lineWidth: 0.5,
      },
   });

   yPosition = (pdf as any).lastAutoTable.finalY + 12;

   // Check if we need a new page
   if (yPosition > pageHeight - 60) {
      pdf.addPage();
      yPosition = 15;
   }

   // 3. COLLECTION STATUS ANALYSIS
   pdf.setFontSize(11);
   pdf.setFont("Arial", "bold");
   pdf.text("3. COLLECTION STATUS ANALYSIS", 15, yPosition);
   yPosition += 6;

   const totalAmount = data.rmRecoveredAmount + data.rmOutStandingAmount + data.rmOverdueAmount;
   const recoveredPercent =
      totalAmount > 0 ? ((data.rmRecoveredAmount / totalAmount) * 100).toFixed(2) : "0.00";
   const outstandingPercent =
      totalAmount > 0 ? ((data.rmOutStandingAmount / totalAmount) * 100).toFixed(2) : "0.00";
   const overduePercent =
      totalAmount > 0 ? ((data.rmOverdueAmount / totalAmount) * 100).toFixed(2) : "0.00";

   const collectionData = [
      ["Collection Status", "Amount (BDT)", "Percentage (%)", "Description"],
      [
         "Successfully Recovered",
         formatBDT(data.rmRecoveredAmount),
         recoveredPercent,
         "Amount successfully collected from customers",
      ],
      [
         "Outstanding (Pending)",
         formatBDT(data.rmOutStandingAmount),
         outstandingPercent,
         "Amount pending for collection action",
      ],
      [
         "Overdue (Past Due)",
         formatBDT(data.rmOverdueAmount),
         overduePercent,
         "Amount exceeding due date",
      ],
      ["TOTAL COLLECTION", formatBDT(totalAmount), "100.00", "Total amount across all statuses"],
   ];

   autoTable(pdf, {
      startY: yPosition,
      head: [collectionData[0]],
      body: collectionData.slice(1),
      margin: { left: 15, right: 15 },
      theme: "grid",
      headStyles: {
         fillColor: [0, 0, 0],
         textColor: [255, 255, 255],
         fontSize: 10,
         fontStyle: "bold",
         halign: "left",
         valign: "middle",
      },
      bodyStyles: {
         fontSize: 9,
         halign: "left",
         valign: "middle",
      },
      alternateRowStyles: {
         fillColor: [245, 245, 245],
      },
      styles: {
         lineColor: [0, 0, 0],
         lineWidth: 0.5,
      },
      didDrawPage: function () {
         pdf.setFontSize(8);
         pdf.setTextColor(0, 0, 0);
      },
   });

   yPosition = (pdf as any).lastAutoTable.finalY + 12;

   // Check if we need a new page
   if (yPosition > pageHeight - 60) {
      pdf.addPage();
      yPosition = 15;
   }

   // 4. PERFORMANCE ACHIEVEMENT ANALYSIS
   pdf.setFontSize(11);
   pdf.setFont("Arial", "bold");
   pdf.text("4. PERFORMANCE ACHIEVEMENT ANALYSIS", 15, yPosition);
   yPosition += 6;

   const performanceRate =
      data.rmTarget > 0 ? ((data.rmRecoveredAmount / data.rmTarget) * 100).toFixed(2) : "0.00";
   const remainingTarget = Math.max(0, data.rmTarget - data.rmRecoveredAmount);

   let performanceStatus = "Below Target";
   if (Number(performanceRate) >= 100) {
      performanceStatus = "Target Exceeded - Excellent Performance";
   } else if (Number(performanceRate) >= 80) {
      performanceStatus = "On Track - Good Progress";
   } else if (Number(performanceRate) >= 60) {
      performanceStatus = "Moderate Progress";
   } else {
      performanceStatus = "Below Target - Requires Attention";
   }

   const performanceData = [
      ["Performance Metric", "Value", "Analysis/Remarks"],
      ["Annual Target Amount", formatBDT(data.rmTarget), "Total recovery target for the period"],
      [
         "Amount Recovered to Date",
         formatBDT(data.rmRecoveredAmount),
         "Amount successfully recovered against target",
      ],
      ["Performance Achievement Rate", `${performanceRate}%`, performanceStatus],
      [
         "Remaining Target to Achieve",
         formatBDT(remainingTarget),
         remainingTarget > 0 ? "Additional amount to be recovered" : "Target Already Achieved",
      ],
   ];

   autoTable(pdf, {
      startY: yPosition,
      head: [performanceData[0]],
      body: performanceData.slice(1),
      margin: { left: 15, right: 15 },
      theme: "grid",
      headStyles: {
         fillColor: [0, 0, 0],
         textColor: [255, 255, 255],
         fontSize: 10,
         fontStyle: "bold",
         halign: "left",
         valign: "middle",
      },
      bodyStyles: {
         fontSize: 9,
         halign: "left",
         valign: "middle",
      },
      alternateRowStyles: {
         fillColor: [245, 245, 245],
      },
      styles: {
         lineColor: [0, 0, 0],
         lineWidth: 0.5,
      },
   });

   yPosition = (pdf as any).lastAutoTable.finalY + 15;

   // Signature Section
   const signatureY = pageHeight - 30;
   pdf.setFontSize(9);
   pdf.setFont("Arial", "normal");
   pdf.text(
      "This report is generated by the Recovery Management System of P2M Bank Limited.",
      15,
      signatureY
   );
   pdf.text("Authorized by: ___________________     Date: ___________________", 15, signatureY + 8);

   // Footer with line
   const footerY = pageHeight - 10;
   pdf.setFontSize(8);
   pdf.setTextColor(0, 0, 0);
   pdf.setLineWidth(0.5);
   pdf.line(15, footerY - 5, pageWidth - 15, footerY - 5);
   pdf.text(`${bankName} | Confidential`, 15, footerY);
   pdf.text(`Page 1 of 1`, pageWidth - 40, footerY);

   // Save PDF
   pdf.save(`P2M_RM_Dashboard_Report_${moment().format("YYYY-MM-DD_HH-mm-ss")}.pdf`);
};

/**
 * Generate Monthly Recovery Report (Black & White, Table Only, P2M Bank Format)
 * @param data Monthly data array
 * @param options Report customization options
 */
export const generateMonthlyRecoveryReport = (data: any[], options: ReportOptions = {}): void => {
   const {
      title = "Monthly Recovery Performance Report",
      companyName = "PRIME TWO MILLION (P2M) BANK LIMITED",
      reportDate = moment().format("DD MMMM YYYY"),
      generatedBy = "System Generated",
      bankName = "P2M Bank",
   } = options;

   const pdf = new jsPDF({
      orientation: "landscape",
      unit: "mm",
      format: "a4",
   });

   const pageWidth = pdf.internal.pageSize.getWidth();
   const pageHeight = pdf.internal.pageSize.getHeight();
   let yPosition = 15;

   // Set text color to black
   pdf.setTextColor(0, 0, 0);

   // Header - Professional Bank Header
   pdf.setFontSize(16);
   pdf.setFont("Arial", "bold");
   pdf.text(companyName, pageWidth / 2, yPosition, { align: "center" });

   yPosition += 8;
   pdf.setFontSize(12);
   pdf.setFont("Arial", "bold");
   pdf.text(title, pageWidth / 2, yPosition, { align: "center" });

   yPosition += 7;
   pdf.setFontSize(9);
   pdf.setFont("Arial", "normal");
   pdf.text(`Report Period: ${reportDate}`, pageWidth / 2, yPosition, {
      align: "center",
   });

   yPosition += 5;
   pdf.text(
      `Generated By: ${generatedBy} | Generated On: ${moment().format("DD MMM YYYY HH:mm:ss")}`,
      pageWidth / 2,
      yPosition,
      {
         align: "center",
      }
   );

   yPosition += 10;

   // Add horizontal line
   pdf.setDrawColor(0, 0, 0);
   pdf.setLineWidth(0.5);
   pdf.line(15, yPosition, pageWidth - 15, yPosition);

   yPosition += 8;

   // Section Title
   pdf.setFontSize(11);
   pdf.setFont("Arial", "bold");
   pdf.text("MONTHLY RECOVERY PERFORMANCE DETAILS", 15, yPosition);
   yPosition += 6;

   // Monthly Table
   const monthlyTableData = [
      [
         "Month",
         "Annual Target (BDT)",
         "Amount Collected (BDT)",
         "Variance (BDT)",
         "Achievement Rate (%)",
         "Status",
      ],
      ...data.map((item) => {
         const target = item.target || 0;
         const collection = item.collection || 0;
         const achievement = target > 0 ? ((collection / target) * 100).toFixed(2) : "0.00";
         const difference = collection - target;
         const status =
            Number(achievement) >= 100
               ? "Achieved"
               : Number(achievement) >= 80
               ? "On Track"
               : "Below Target";

         return [
            item.monthName || item.month || "-",
            formatBDT(target),
            formatBDT(collection),
            difference >= 0 ? `+${formatBDT(difference)}` : formatBDT(difference),
            `${achievement}%`,
            status,
         ];
      }),
   ];

   autoTable(pdf, {
      startY: yPosition,
      head: [monthlyTableData[0]],
      body: monthlyTableData.slice(1),
      margin: { left: 15, right: 15 },
      theme: "grid",
      headStyles: {
         fillColor: [0, 0, 0],
         textColor: [255, 255, 255],
         fontSize: 9,
         fontStyle: "bold",
         halign: "center",
         valign: "middle",
      },
      bodyStyles: {
         fontSize: 8,
         halign: "center",
         valign: "middle",
      },
      alternateRowStyles: {
         fillColor: [245, 245, 245],
      },
      styles: {
         lineColor: [0, 0, 0],
         lineWidth: 0.5,
      },
   });

   // Signature Section
   const signatureY = pageHeight - 25;
   pdf.setFontSize(9);
   pdf.setFont("Arial", "normal");
   pdf.text(
      "Authorized Approver: ___________________     Date: ___________________",
      15,
      signatureY
   );

   // Footer with line
   const footerY = pageHeight - 8;
   pdf.setFontSize(8);
   pdf.setTextColor(0, 0, 0);
   pdf.setLineWidth(0.5);
   pdf.line(15, footerY - 3, pageWidth - 15, footerY - 3);
   pdf.text(`${bankName} | Confidential Document`, 15, footerY);
   pdf.text(`Page 1 of 1`, pageWidth - 40, footerY);

   pdf.save(`P2M_Monthly_Recovery_Report_${moment().format("YYYY-MM-DD_HH-mm-ss")}.pdf`);
};

export default {
   formatBDT,
   formatNumber,
   generateRMDashboardReport,
   generateMonthlyRecoveryReport,
};
